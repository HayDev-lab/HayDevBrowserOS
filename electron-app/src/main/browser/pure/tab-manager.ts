/**
 * Pure tab list state machine.
 *
 * NO electron import — fully unit-testable.
 *
 * The runtime `BrowserCore` keeps a `TabManager` instance and syncs it with
 * real WebContentsView instances. Tab state changes are emitted via the
 * `TabManagerEvents` callback interface so the runtime / renderer can react.
 *
 * Concurrency model: single-threaded. All mutations are synchronous. The
 * runtime owner is responsible for any async coordination (e.g. awaiting
 * `webContents.loadURL`) before updating the tab's `loadState`.
 */
import type { TabState, TabLoadState } from '@shared/browser-types';

export interface TabManagerEvents {
  onTabOpened?: (tab: TabState) => void;
  onTabClosed?: (tabId: string, nextActiveId: string | null) => void;
  onTabActivated?: (tabId: string, prevId: string | null) => void;
  onTabUpdated?: (tab: TabState) => void;
  onTabReordered?: (order: string[]) => void;
}

export interface OpenTabOptions {
  url?: string;
  activate?: boolean;
  incognito?: boolean;
  background?: boolean;
  /** Optional explicit id (for session restore). If omitted, a uuid is generated. */
  id?: string;
  title?: string;
}

export interface CloseTabOptions {
  /**
   * Which tab to activate after closing. Defaults to the right neighbour,
   * falling back to the left neighbour, falling back to null.
   */
  activateAfterClose?: 'right' | 'left' | 'none';
}

export interface TabManagerSnapshot {
  tabs: TabState[];
  order: string[];
  activeId: string | null;
}

let _tabIdCounter = 0;
function generateTabId(): string {
  _tabIdCounter += 1;
  // Stable enough for tests; runtime uses the same scheme. Production
  // UUIDs can be generated by the runtime owner and passed via `OpenTabOptions.id`.
  return `tab_${Date.now().toString(36)}_${_tabIdCounter.toString(36)}`;
}

export class TabManager {
  private tabs = new Map<string, TabState>();
  private order: string[] = [];
  private activeId: string | null = null;

  constructor(
    private events: TabManagerEvents = {},
    private idGenerator: () => string = generateTabId,
    private now: () => number = () => Date.now()
  ) {}

  /**
   * Open a new tab.
   * Returns the new tab's id.
   */
  openTab(opts: OpenTabOptions = {}): string {
    const id = opts.id ?? this.idGenerator();
    if (this.tabs.has(id)) {
      throw new Error(`TabManager.openTab: tab id already exists: ${id}`);
    }
    const now = this.now();
    const tab: TabState = {
      id,
      url: '',
      pendingUrl: opts.url ?? '',
      title: opts.title ?? opts.url ?? 'New Tab',
      loadState: 'idle' as TabLoadState,
      error: null,
      canGoBack: false,
      canGoForward: false,
      isIncognito: opts.incognito === true,
      isActive: false,
      isAudioPlaying: false,
      createdAt: now,
      lastActivatedAt: now,
    };
    this.tabs.set(id, tab);
    this.order.push(id);

    const shouldActivate = opts.activate !== false && opts.background !== true;
    if (shouldActivate) {
      this.activateTab(id);
    } else {
      this.events.onTabOpened?.(tab);
    }
    return id;
  }

  /**
   * Close a tab. Returns true if the tab was found and closed.
   * Side effect: activates the right neighbour (or left, or none) per `opts`.
   */
  closeTab(tabId: string, opts: CloseTabOptions = {}): boolean {
    const tab = this.tabs.get(tabId);
    if (!tab) return false;

    const idx = this.order.indexOf(tabId);
    if (idx === -1) {
      // Inconsistent state — remove the tab entry but skip re-activation.
      this.tabs.delete(tabId);
      this.events.onTabClosed?.(tabId, this.activeId);
      return true;
    }

    this.order.splice(idx, 1);
    this.tabs.delete(tabId);

    let nextActive: string | null = null;
    if (this.activeId === tabId) {
      const strategy = opts.activateAfterClose ?? 'right';
      if (strategy === 'right' && idx < this.order.length) {
        nextActive = this.order[idx];
      } else if (strategy === 'left' && idx > 0) {
        nextActive = this.order[idx - 1];
      } else if (this.order.length > 0) {
        // Fallback: pick the closest tab if `none` was requested but we still
        // need an active tab.
        nextActive = this.order[Math.min(idx, this.order.length - 1)];
      } else {
        nextActive = null;
      }
      this.setActive(nextActive);
    } else {
      nextActive = this.activeId;
    }

    this.events.onTabClosed?.(tabId, nextActive);
    return true;
  }

  /**
   * Activate a tab. Returns true if the tab was found and activated.
   */
  activateTab(tabId: string): boolean {
    const tab = this.tabs.get(tabId);
    if (!tab) return false;
    if (this.activeId === tabId) return true;

    const prevId = this.activeId;
    if (prevId) {
      const prev = this.tabs.get(prevId);
      if (prev) {
        prev.isActive = false;
        this.events.onTabUpdated?.(prev);
      }
    }
    this.activeId = tabId;
    tab.isActive = true;
    tab.lastActivatedAt = this.now();
    this.events.onTabUpdated?.(tab);
    this.events.onTabActivated?.(tabId, prevId);
    return true;
  }

  /** Returns the active tab id (or null). */
  getActiveId(): string | null {
    return this.activeId;
  }

  getActiveTab(): TabState | null {
    return this.activeId ? this.tabs.get(this.activeId) ?? null : null;
  }

  getTab(tabId: string): TabState | null {
    return this.tabs.get(tabId) ?? null;
  }

  listTabs(): TabState[] {
    return this.order.map((id) => this.tabs.get(id)!).filter(Boolean);
  }

  getOrder(): string[] {
    return [...this.order];
  }

  /**
   * Apply a partial update to a tab and emit `onTabUpdated`.
   * Returns true if the tab was found and updated.
   */
  updateTab(tabId: string, patch: Partial<TabState>): boolean {
    const tab = this.tabs.get(tabId);
    if (!tab) return false;
    // `id` and `isActive` are managed internally; ignore them in patches.
    const { id: _ignoredId, isActive: _ignoredActive, ...rest } = patch;
    Object.assign(tab, rest);
    this.events.onTabUpdated?.(tab);
    return true;
  }

  /**
   * Reorder tabs. `newOrder` must contain exactly the same ids as the current
   * order (no duplicates, no missing ids). Returns true on success.
   */
  reorder(newOrder: string[]): boolean {
    if (newOrder.length !== this.order.length) return false;
    const incoming = new Set(newOrder);
    if (incoming.size !== newOrder.length) return false;
    for (const id of this.order) {
      if (!incoming.has(id)) return false;
    }
    this.order = [...newOrder];
    this.events.onTabReordered?.(this.order);
    return true;
  }

  /** Move a tab to a new index. Returns true on success. */
  moveTab(tabId: string, newIndex: number): boolean {
    const idx = this.order.indexOf(tabId);
    if (idx === -1) return false;
    if (newIndex < 0 || newIndex >= this.order.length) return false;
    if (idx === newIndex) return true;
    this.order.splice(idx, 1);
    this.order.splice(newIndex, 0, tabId);
    this.events.onTabReordered?.(this.order);
    return true;
  }

  /** Snapshot for persistence / session restore. */
  snapshot(): TabManagerSnapshot {
    return {
      tabs: this.listTabs().map((t) => ({ ...t })),
      order: [...this.order],
      activeId: this.activeId,
    };
  }

  /** Restore from a snapshot. Replaces all current state. */
  restore(snapshot: TabManagerSnapshot): void {
    this.tabs.clear();
    this.order = [];
    this.activeId = null;
    for (const tabState of snapshot.tabs) {
      const tab: TabState = {
        ...tabState,
        isActive: false, // we'll re-set the active one below
        loadState: 'idle',
      };
      this.tabs.set(tab.id, tab);
      this.order.push(tab.id);
    }
    // Preserve original order if the snapshot's order differs from the
    // order in `tabs`.
    if (snapshot.order.length === this.order.length) {
      this.order = [...snapshot.order];
    }
    if (snapshot.activeId && this.tabs.has(snapshot.activeId)) {
      this.setActive(snapshot.activeId);
    } else if (this.order.length > 0) {
      this.setActive(this.order[0]);
    }
  }

  /** Count of open tabs. */
  size(): number {
    return this.tabs.size;
  }

  // ---------------------------------------------------------------------------
  // Internal helpers
  // ---------------------------------------------------------------------------
  private setActive(tabId: string | null): void {
    if (tabId === null) {
      this.activeId = null;
      return;
    }
    const tab = this.tabs.get(tabId);
    if (!tab) return;
    this.activeId = tabId;
    tab.isActive = true;
    tab.lastActivatedAt = this.now();
  }
}
